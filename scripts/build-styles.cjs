'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const application = ['tokens.css', 'foundation.css', 'training.css', 'layout.css', 'sandbox.css', 'machine.css'];
const sources = [...application, 'account.css', 'typography.css'];
const read = name => fs.readFileSync(path.join(root, 'styles', name), 'utf8').trim();
const render = names => '/* Generated by scripts/build-styles.cjs. Edit styles/ sources. */\n' +
  names.map(name => '/* Source: styles/' + name + ' */\n' + read(name)).join('\n\n') + '\n';

function outputs() {
  return {
    'app.css': render(application),
    // Stable URLs for older clients and standalone account pages.
    'style.css': render(['tokens.css', 'foundation.css']),
    'workshop-theme.css': render(['training.css']),
    'light-theme.css': render(['layout.css']),
    'sandbox.css': render(['sandbox.css']),
    'real-machine.css': render(['machine.css']),
    'server/public/account.css': render(['account.css']),
    'typography.css': render(['tokens.css', 'typography.css']),
  };
}
function build() {
  for (const [file, content] of Object.entries(outputs())) fs.writeFileSync(path.join(root, file), content);
}
function check() {
  for (const [file, content] of Object.entries(outputs())) {
    if (fs.readFileSync(path.join(root, file), 'utf8') !== content) {
      throw Error(file + ' is stale: run npm run build:styles');
    }
  }
}
if (require.main === module) {
  if (process.argv.includes('--check')) check();
  else build();
  console.log('Canonical style sources and generated assets verified.');
}
module.exports = { sources, outputs, build, check };
