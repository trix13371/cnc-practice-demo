"use strict";
const assert = require("node:assert/strict");
const milling = require("../milling-course-model.js");
const {preview,run} = milling.route25d;
const program = (...lines)=>lines.join("\n");
const pocket = (...lines)=>preview("pocket",program(...lines));
const entry = ["G0 X9 Y7 Z20","G0 X9 Y7 Z2","M03"];
const end = ["G0 X9 Y7 Z12","M05"];
const firstLayer = ["G1 X9 Y7 Z-1","G1 X13 Y7 Z-1","G1 X18 Y7 Z-1"];
const full = pocket(...entry,...firstLayer,"G1 X18 Y7 Z-2","G1 X9 Y7 Z-2",...end);
assert(full.ok,JSON.stringify(full.incident));
assert.equal(full.cuts.length,5);
assert.equal(full.spindle,false);
assert.equal(full.position.z,12);
assert(full.material.removedArea.min>0);
assert(full.material.reachableRemainingArea.min>0,"A safe lane does not finish a pocket");
const repeated = pocket(...entry,...firstLayer,"G1 X18 Y7 Z-2","G1 X9 Y7 Z-2","G1 X18 Y7 Z-2","G1 X9 Y7 Z-2",...end);
assert.deepEqual(repeated.material.removedArea,full.material.removedArea,"Repeat passes cannot inflate removed area");
const shallow = pocket(...entry,"G1 X9 Y7 Z-1",...end);
assert(shallow.ok);
assert.deepEqual(shallow.material.removedArea,{min:0,max:0},"One layer does not remove material at the floor");

const direct = pocket(...entry,"G1 X9 Y7 Z-2",...end);
assert.equal(direct.incident.code,"DEPTH");
assert.equal(direct.incident.line,4);
assert.equal(direct.cuts.length,0);
assert.deepEqual(direct.position,{x:9,y:7,z:2});
const wrongLine = pocket(...entry,...firstLayer,"G1 X18 Y7 Z-2","G1 X18 Y8 Z-2");
assert.equal(wrongLine.incident.code,"DEPTH","Preparing a nearby lane does not establish the deeper lane");
assert.equal(wrongLine.cuts.length,4,"Failed move adds no cut");
assert.deepEqual(wrongLine.position,{x:18,y:7,z:-2});
const gap = pocket(...entry,"G1 X9 Y7 Z-1","G1 X12 Y7 Z-1","G0 X12 Y7 Z2",
  "G0 X14 Y7 Z2","G1 X14 Y7 Z-1","G1 X18 Y7 Z-1","G1 X18 Y7 Z-2","G1 X9 Y7 Z-2",...end);
assert.equal(gap.incident.code,"DEPTH","Separated supporting segments cannot certify the missing interval");
assert.equal(pocket(...entry,...firstLayer,"G1 X18 Y7 Z-2.1").incident.code,"FLOOR");
assert.equal(pocket(...entry,"G1 X10 Y7 Z-1").incident.code,"INCLINED");
assert.equal(pocket("G0 X9 Y7 Z20","G0 X9 Y7 Z1").incident.code,"RAPID_DEPTH");
assert.equal(pocket(...entry,"G0 X9 Y7 Z-1").incident.code,"RAPID_STOCK");
assert.equal(pocket(...entry,"G1 X9 Y7 Z-1","G0 X11 Y7 Z-1").incident.code,"RAPID_STOCK");
assert.equal(pocket(...entry.slice(0,2),"G1 X9 Y7 Z-1").incident.code,"SPINDLE");
assert.equal(pocket(...entry,"G1 X9 Y7 Z-1","G1 X8.9 Y7 Z-1").incident.code,"POCKET_WALL");
assert.equal(pocket(...entry,"G1 X9 Y7 Z-1","M05").incident.code,"SPINDLE_CLEARANCE");
assert.equal(pocket(...entry,"G1 X9 Y7 Z-1","G0 X9 Y7 Z2","M05").incident.code,"END_UNSAFE");
assert.equal(pocket(...entry,"G1 X9 Y7 Z-1",end[0]).incident.code,"END_UNSAFE");
assert.equal(pocket("", "G0 X9 Y7 Z20","G2 X9 Y7 Z20").incident.line,3);
assert.equal(pocket("G1 X9 Y7 ZNaN").incident.code,"COMMAND");
assert.equal(pocket("G0 X999 Y7 Z20").incident.code,"TRAVEL");

const finish = ["G0 X46 Y28 Z20","G0 X-10 Y5 Z20"];
const approach = ["G0 X12 Y28 Z20","G0 X12 Y28 Z5"];
const high = pocket(...approach,"G0 X12 Y28 Z20",...finish);
const low = pocket(...approach,"G0 X46 Y28 Z5",...finish);
assert(high.ok);
assert.equal(low.incident.code,"FIXTURE");
assert.deepEqual(low.incident.point,{x:22,y:28,z:5});
assert.deepEqual(low.position,{x:12,y:28,z:5},"No motion is committed for a crossing segment");
assert.deepEqual(high.position,{x:-10,y:5,z:20});
const holder = preview("contour",program("G0 X12 Y20 Z20","G0 X12 Y20 Z2","M03","G1 X12 Y20 Z-1","G1 X22 Y20 Z-1"));
assert.equal(holder.incident.code,"HOLDER_FIXTURE");
assert.deepEqual(holder.incident.point,{x:13,y:20,z:-1});
assert.equal(holder.cuts.length,1);
const body = pocket("G0 X40 Y-4 Z20","G0 X55 Y-4 Z20");
assert.equal(body.incident.code,"MACHINE_BODY");
assert.deepEqual(body.incident.point,{x:42,y:-4,z:20});
assert.equal(body.incident.part,"Державка");
const around = preview("contour",program("G0 X2 Y8 Z20","G0 X2 Y8 Z2","M03","G1 X2 Y8 Z-1",
  "G1 X2 Y4 Z-1","G1 X2 Y4 Z-2","G1 X2 Y8 Z-2","G0 X2 Y8 Z12","M05"));
assert(around.ok,JSON.stringify(around.incident));
assert(around.material.removedArea.min>0);
const gouge = preview("contour",program("G0 X2 Y8 Z20","G0 X2 Y8 Z2","M03","G1 X2 Y8 Z-1","G1 X23 Y8 Z-1"));
assert.equal(gouge.incident.code,"PART_GOUGE");
assert.equal(gouge.cuts.length,1);

const unprepared = milling.plate.create(), before=structuredClone(unprepared);
assert.equal(run(unprepared,"pocket",[{type:"spindle",value:true}]).incident.code,"START");
assert.deepEqual(unprepared,before);
assert.equal(milling.plate.restore(milling.plate.snapshot(unprepared)).cuts,0);
console.log("2.5D milling: layered pockets and contour, swept collisions, floor, safe finish, line diagnostics and isolated stock passed.");
