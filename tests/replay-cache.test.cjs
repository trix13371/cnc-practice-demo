'use strict';
const assert = require('node:assert/strict');
const { create } = require('../replay-cache-model.js');
const cache = create({ maxEntries: 2, maxBytes: 1024 });
const raw = { version: 1, events: [{ type: 'reference' }] };
const state = { complete: true, profile: [32, 28] };
cache.remember(raw, state);
state.profile[0] = 0;
assert.equal(cache.get(raw).profile[0], 32);
cache.get(raw).profile[0] = 9;
assert.equal(cache.get(raw).profile[0], 32, 'Returned state must not mutate verified cache');
assert.equal(cache.get({ ...raw, complete: true }), null, 'Derived-field injection is a different input');
assert.equal(cache.get({ ...raw, extra: undefined }), null, 'Undefined keys must not alias a validated JSON input');
assert.equal(cache.get({ ...raw, extra: NaN }), null);
assert.equal(cache.get({ toJSON: () => raw }), null, 'A toJSON hook must not impersonate a verified journal');
assert.equal(cache.get({ ...raw, events: [{ toJSON: () => raw.events[0] }] }), null);
cache.remember({ id: 2 }, { value: 2 });
cache.get(raw);
cache.remember({ id: 3 }, { value: 3 });
assert.equal(cache.get({ id: 2 }), null, 'Least recently used entry evicted');
assert(cache.get(raw));
cache.remember({ id: 4 }, { value: 'x'.repeat(2048) });
assert.equal(cache.get({ id: 4 }), null, 'Oversized states must not exceed memory budget');
assert(cache.get(raw), 'Uncacheable entry must not flush useful data');
console.log('Verified replay cache: JSON identity, copy isolation, LRU and byte bounds passed.');
